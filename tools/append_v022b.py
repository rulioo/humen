# -*- coding: utf-8 -*-
"""给 v0.22 行补 ⑦⑧ 两条：标记配色的对比度缺陷，以及材质资产的"改了不生效"陷阱。"""
import io

P = 'design.md'
s = io.open(P, encoding='utf-8', newline='').read()

ANCHOR = '**属作者的设计决定，未擅动。** |\n'
assert s.count(ANCHOR) == 1, '锚点命中 %d 次' % s.count(ANCHOR)

ADD = (
    '**属作者的设计决定，未擅动。**<br>'
    '⑦ ★ **改完判据渲出来一看，又发现一个配色缺陷：标记压在它自己那类地形上是隐形的。** '
    '第一版配色按「语义」挑（篝火黄／作物绿／锻铁青／电弧紫），看着合理，实测两档看不见：<br>'
    '· **村落绿**（0.45,0.85,0.42）压在它自己的大陆上 —— 大陆 3 整块是植被绿，'
    '**774 px 的村落标记肉眼一个都找不出来**。而这不是巧合，是<b>必然</b>：'
    '聚落只长在能种地的地方，能种地的地方就是绿的，<b>绿标记永远落在绿地上</b>；<br>'
    '· **游群橙黄**（0.95,0.72,0.35）压在裸岩与漠土上 —— 大陆 1/2 地表是土黄与灰，标记糊在里面。<br>'
    '改为对着<b>地形调色板</b>选色（本工程地形只有五种色：植被绿／漠土黄／冰白／岩灰／海蓝），'
    '四档一律取饱和且非地球的色相：<b>橙红／明黄／亮青／品红</b>，每个与那五种色至少在一个通道上差 60 以上。'
    '重渲后同一片大陆 3 上，明黄的村落与亮青的铁器、品红的工业<b>一眼可分</b>。<br>'
    '　⚠️ 顺带修好 ⑨ 那条假阳性：原「锻铁冷青」的 R 通道与冰白太近（冰是浅蓝），'
    '实测大陆 1 报 1 px 的假「铁器」；新亮青把 R 与冰白拉开 150，重渲后<b>归零</b>。<br>'
    '　**教训：标记配色要对着「地形调色板」选，不能对着「语义」选。** 前者是约束，后者只是偏好。<br>'
    '⑧ ⚠️ **差点栽进一个"改了不生效"的陷阱：材质资产只创建不更新。** '
    '`PlanetSceneBuilder.EnsureMarkerMaterialAssets` 原本写的是'
    '「资产已存在就 <c>continue</c>」—— 于是<b>改了 <c>Colors[]</c> 再重建场景，材质还是旧的</b>，'
    '而且一句错都不报。症状会是「我明明改了配色，渲出来一点没变」，'
    '最坏的下场是误判成"配色改了没用"而放弃一个正确的修改。'
    '改为：已存在则<b>比对并更新颜色</b>再 <c>SetDirty</c>。'
    '这与 §7.3「能被代码重新算出来的，就不要存成手工状态」是同一条原则 —— '
    '<b>颜色由代码定义，资产只是它的落盘副本，副本必须跟着源走</b>。<br>'
    '　⚠️ 同时删掉已失去语义的 <c>Tribe_Town.mat</c>：它是旧分档的遗留，'
    '名字里的 "Town" 与更正后的判据（那里其实是<b>工业</b>）冲突，留着迟早误导人。'
    '**旧的判据可以改，旧的名字必须删。** |\n'
)

io.open(P, 'w', encoding='utf-8', newline='').write(s.replace(ANCHOR, ADD, 1))
print('ok')
